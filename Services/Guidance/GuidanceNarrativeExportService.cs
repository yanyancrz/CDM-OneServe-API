namespace CDM_OneServe_API.Services.Guidance;

/// <summary>
/// Professional A4 exports for narrative reports. Both formats use the same
/// content order and deliberately exclude private notes unless the caller is
/// the authoring counselor.
/// </summary>
public static class GuidanceNarrativeExportService
{
    private const string Institution = "Colegio de Dagupan";
    private const string Office = "Guidance and Counseling Center";

    static GuidanceNarrativeExportService()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public static string FileName(NarrativeReportDetailDto report, string extension)
    {
        var basis = string.IsNullOrWhiteSpace(report.ReportNumber)
            ? $"narrative-report-{report.Id}"
            : report.ReportNumber;

        var safe = new string(basis.Select(c => char.IsLetterOrDigit(c) || c is '-' or '_' ? c : '-').ToArray());
        return $"{safe}.{extension}";
    }

    // =====================================================
    // DOCX
    // =====================================================

    public static byte[] BuildDocx(NarrativeReportDetailDto report, bool includePrivateNotes)
    {
        using var stream = new MemoryStream();

        using (var document = WordprocessingDocument.Create(stream, WordprocessingDocumentType.Document, true))
        {
            var main = document.AddMainDocumentPart();
            main.Document = new DocumentFormat.OpenXml.Wordprocessing.Document();
            var body = main.Document.AppendChild(new Body());

            // ---- letterhead, repeats on every page via the header part ----
            var headerPart = AddHeader(main);
            var footerPart = AddFooter(main, report);

            AddParagraph(body, Institution, bold: true, size: 26, center: true, color: "106A2E");
            AddParagraph(body, Office, size: 20, center: true, color: "4B5563");
            AddParagraph(body, "NARRATIVE REPORT", bold: true, size: 32, center: true, spaceAfter: 120);
            AddRule(body);

            AddKeyValueTable(body, report);

            AddSection(body, "Session Summary", report.SessionSummary);
            AddSection(body, "Session Objectives", report.SessionObjectives);
            AddSection(body, "Observations", report.Observations);
            AddSection(body, "Interventions / Actions Taken", report.Interventions);
            AddSection(body, "Recommendations", report.Recommendations);
            AddSection(body, "Follow-up Plan", report.FollowUpPlan);

            if (includePrivateNotes && !string.IsNullOrWhiteSpace(report.PrivateNotes))
                AddSection(body, "Private Notes (Counselor Only)", report.PrivateNotes);

            if (report.Attachments.Count > 0)
            {
                AddHeading(body, "Supporting Attachments");
                foreach (var attachment in report.Attachments)
                {
                    AddParagraph(
                        body,
                        $"• {attachment.FileName} ({FormatSize(attachment.SizeBytes)}) - uploaded {attachment.UploadedAt:MMM d, yyyy}",
                        size: 20,
                        spaceAfter: 40);
                }
            }

            AddParagraph(body, "", spaceAfter: 160);
            AddParagraph(body, "Prepared by:", size: 20, spaceAfter: 40);
            AddParagraph(body, report.CounselorName, bold: true, size: 22, spaceAfter: 20);
            AddParagraph(body, "Guidance Counselor", size: 20, color: "4B5563", spaceAfter: 240);
            AddParagraph(
                body,
                $"Generated by CDM OneServe on {GuidanceClock.Now:MMMM d, yyyy h:mm tt}",
                size: 18,
                color: "6B7280");

            // sectPr is the last child of the body and links the header/footer parts.
            AddSectionProperties(body, main.GetIdOfPart(headerPart), main.GetIdOfPart(footerPart));

            main.Document.Save();
        }

        return stream.ToArray();
    }

    private static void AddSectionProperties(Body body, string headerId, string footerId)
    {
        body.AppendChild(new SectionProperties(
            new HeaderReference { Type = HeaderFooterValues.Default, Id = headerId },
            new FooterReference { Type = HeaderFooterValues.Default, Id = footerId },
            new DocumentFormat.OpenXml.Wordprocessing.PageSize { Width = 11906, Height = 16838 },   // A4 portrait in twips
            new PageMargin
            {
                Top = 1134,
                Right = 1134,
                Bottom = 1134,
                Left = 1134,
                Header = 567,
                Footer = 567,
                Gutter = 0
            }));
    }

    private static HeaderPart AddHeader(MainDocumentPart main)
    {
        var headerPart = main.AddNewPart<HeaderPart>();
        var header = new Header();

        var paragraph = new Paragraph(new ParagraphProperties(
            new ParagraphBorders(new BottomBorder { Val = BorderValues.Single, Size = 6, Color = "D1D5DB" }),
            new SpacingBetweenLines { After = "80" }));

        paragraph.AppendChild(Run(Institution, size: 18, bold: true, color: "106A2E"));
        paragraph.AppendChild(new Run(new Text("  ·  ") { Space = SpaceProcessingModeValues.Preserve }, RunProps(size: 18, color: "9CA3AF")));
        paragraph.AppendChild(Run(Office, size: 18, color: "6B7280"));

        header.AppendChild(paragraph);
        headerPart.Header = header;
        return headerPart;
    }

    private static FooterPart AddFooter(MainDocumentPart main, NarrativeReportDetailDto report)
    {
        var footerPart = main.AddNewPart<FooterPart>();
        var footer = new Footer();

        var paragraph = new Paragraph(new ParagraphProperties(
            new ParagraphBorders(new TopBorder { Val = BorderValues.Single, Size = 6, Color = "D1D5DB" }),
            new Justification { Val = JustificationValues.Center },
            new SpacingBetweenLines { Before = "80" }));

        var reference = string.IsNullOrWhiteSpace(report.ReportNumber)
            ? $"Report #{report.Id}"
            : report.ReportNumber;

        paragraph.AppendChild(Run($"{reference}  ·  Page ", size: 16, color: "6B7280"));
        paragraph.AppendChild(Field("PAGE"));
        paragraph.AppendChild(Run(" of ", size: 16, color: "6B7280"));
        paragraph.AppendChild(Field("NUMPAGES"));

        footer.AppendChild(paragraph);
        footerPart.Footer = footer;
        return footerPart;
    }

    private static Run Field(string instruction)
    {
        var run = new Run();

        run.AppendChild(new FieldChar { FieldCharType = FieldCharValues.Begin });
        run.AppendChild(new FieldCode($" {instruction} ") { Space = SpaceProcessingModeValues.Preserve });
        run.AppendChild(new FieldChar { FieldCharType = FieldCharValues.Separate });
        run.AppendChild(new Text("1"));
        run.AppendChild(new FieldChar { FieldCharType = FieldCharValues.End });

        run.RunProperties = RunProps(size: 16, color: "6B7280");
        return run;
    }

    private static void AddKeyValueTable(Body body, NarrativeReportDetailDto report)
    {
        var table = new Table(new TableProperties(
            new TableWidth { Width = "5000", Type = TableWidthUnitValues.Pct },
            new TableBorders(
                new TopBorder { Val = BorderValues.Nil },
                new BottomBorder { Val = BorderValues.Nil },
                new LeftBorder { Val = BorderValues.Nil },
                new RightBorder { Val = BorderValues.Nil },
                new InsideHorizontalBorder { Val = BorderValues.Nil },
                new InsideVerticalBorder { Val = BorderValues.Nil })));

        void Row(string label, string value)
        {
            var tr = new TableRow();

            tr.AppendChild(Cell(label, bold: true, width: "22%", color: "6B7280", size: 18));
            tr.AppendChild(Cell(value, bold: false, width: "78%", color: "1F1F1F", size: 20));
            table.AppendChild(tr);
        }

        Row("Report No.", string.IsNullOrWhiteSpace(report.ReportNumber) ? "(draft)" : report.ReportNumber);
        Row("Subject", $"{report.SubjectName} ({report.SubjectRole})");
        Row("ID Number", report.SubjectIdNumber ?? "—");
        Row("Counselor", report.CounselorName);
        Row("Session Date", FormatDate(report.SessionDate));
        Row("Concern", report.ConcernType ?? "—");
        Row("Status", report.Status);
        if (report.IsConfidential) Row("Confidentiality", "Confidential — restricted report");

        body.AppendChild(table);
        body.AppendChild(new Paragraph(new ParagraphProperties(new SpacingBetweenLines { After = "200" })));
    }

    private static TableCell Cell(string text, bool bold, string width, string color, int size)
    {
        var cell = new TableCell(new TableCellProperties(
            new TableCellWidth { Type = TableWidthUnitValues.Pct, Width = width },
            new TableCellVerticalAlignment { Val = TableVerticalAlignmentValues.Top }));

        cell.AppendChild(new Paragraph(
            new ParagraphProperties(new SpacingBetweenLines { After = "40" }),
            Run(text, size: size, bold: bold, color: color)));

        return cell;
    }

    private static void AddRule(Body body)
    {
        body.AppendChild(new Paragraph(new ParagraphProperties(
            new ParagraphBorders(new BottomBorder { Val = BorderValues.Single, Size = 12, Color = "106A2E" }),
            new SpacingBetweenLines { After = "240" })));
    }

    private static void AddSection(Body body, string heading, string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return;

        AddHeading(body, heading);

        foreach (var block in text.Replace("\r\n", "\n").Split('\n'))
        {
            var line = block.TrimEnd();
            if (line.Length == 0)
            {
                AddParagraph(body, "", spaceAfter: 60);
                continue;
            }

            if (line.TrimStart().StartsWith("- ", StringComparison.Ordinal) ||
                line.TrimStart().StartsWith("• ", StringComparison.Ordinal))
            {
                AddParagraph(body, "• " + line.TrimStart()[2..].Trim(), size: 21, indent: 360, spaceAfter: 60);
            }
            else
            {
                AddParagraph(body, line, size: 21, spaceAfter: 80);
            }
        }
    }

    private static void AddHeading(Body body, string text)
    {
        AddParagraph(body, text.ToUpperInvariant(), bold: true, size: 22, color: "106A2E", spaceBefore: 160, spaceAfter: 80);
    }

    private static void AddParagraph(
        Body body,
        string text,
        bool bold = false,
        int size = 21,
        bool center = false,
        string color = "1F1F1F",
        int spaceBefore = 0,
        int spaceAfter = 0,
        int indent = 0)
    {
        var properties = new ParagraphProperties(
            new SpacingBetweenLines { Before = spaceBefore.ToString(), After = spaceAfter.ToString() });

        if (center) properties.AppendChild(new Justification { Val = JustificationValues.Center });
        if (indent > 0) properties.AppendChild(new Indentation { Left = indent.ToString() });

        body.AppendChild(new Paragraph(properties, Run(text, size: size, bold: bold, color: color)));
    }

    private static Run Run(string text, int size, bool bold = false, string color = "1F1F1F") =>
        new(new Text(text) { Space = SpaceProcessingModeValues.Preserve })
        {
            RunProperties = RunProps(size: size, bold: bold, color: color)
        };

    private static RunProperties RunProps(int size, bool bold = false, string color = "1F1F1F")
    {
        var props = new RunProperties(
            new RunFonts { Ascii = "Calibri", HighAnsi = "Calibri" },
            new FontSize { Val = size.ToString(CultureInfo.InvariantCulture) },
            new WColor { Val = color });

        if (bold) props.AppendChild(new Bold());
        return props;
    }

    private static string FormatDate(string value) =>
        DateOnly.TryParseExact(value, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var d)
            ? d.ToString("MMMM d, yyyy", CultureInfo.InvariantCulture)
            : value;

    private static string FormatSize(long bytes) =>
        bytes >= 1024 * 1024
            ? $"{bytes / (1024d * 1024d):0.0} MB"
            : $"{Math.Max(1, Math.Round(bytes / 1024d)):0} KB";

    // =====================================================
    // PDF
    // =====================================================

    public static byte[] BuildPdf(NarrativeReportDetailDto report, bool includePrivateNotes)
    {
        var document = QDocument.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(10).FontColor("#1F1F1F").LineHeight(1.35f));

                page.Header().Column(column =>
                {
                    column.Item().Row(row =>
                    {
                        row.RelativeItem().Text(Institution).FontSize(10).SemiBold().FontColor("#106A2E");
                        row.ConstantItem(150).AlignRight().Text(Office).FontSize(8).FontColor("#6B7280");
                    });
                    column.Item().PaddingTop(2).LineHorizontal(1).LineColor("#106A2E");
                });

                page.Content().PaddingVertical(14).Column(column =>
                {
                    column.Spacing(6);

                    column.Item().AlignCenter().Text("NARRATIVE REPORT")
                        .FontSize(18).Bold().FontColor("#106A2E");
                    column.Item().AlignCenter().Text("Guidance and Counseling Monitoring")
                        .FontSize(9).FontColor("#6B7280");

                    column.Item().PaddingTop(6).Table(table =>
                    {
                        table.ColumnsDefinition(columns =>
                        {
                            columns.ConstantColumn(95);
                            columns.RelativeColumn();
                        });

                        void Row(string label, string value)
                        {
                            table.Cell().Padding(3).Text(label).FontSize(8).SemiBold().FontColor("#6B7280");
                            table.Cell().Padding(3).Text(value).FontSize(9);
                        }

                        Row("Report No.", string.IsNullOrWhiteSpace(report.ReportNumber) ? "(draft)" : report.ReportNumber);
                        Row("Subject", $"{report.SubjectName} ({report.SubjectRole})");
                        Row("ID Number", report.SubjectIdNumber ?? "—");
                        Row("Counselor", report.CounselorName);
                        Row("Session Date", FormatDate(report.SessionDate));
                        Row("Concern", report.ConcernType ?? "—");
                        Row("Status", report.Status);
                        if (report.IsConfidential) Row("Confidentiality", "Confidential — restricted report");
                    });

                    AddPdfSection(column, "Session Summary", report.SessionSummary);
                    AddPdfSection(column, "Session Objectives", report.SessionObjectives);
                    AddPdfSection(column, "Observations", report.Observations);
                    AddPdfSection(column, "Interventions / Actions Taken", report.Interventions);
                    AddPdfSection(column, "Recommendations", report.Recommendations);
                    AddPdfSection(column, "Follow-up Plan", report.FollowUpPlan);

                    if (includePrivateNotes && !string.IsNullOrWhiteSpace(report.PrivateNotes))
                        AddPdfSection(column, "Private Notes (Counselor Only)", report.PrivateNotes, "#B45309");

                    if (report.Attachments.Count > 0)
                    {
                        column.Item().PaddingTop(8).Text("SUPPORTING ATTACHMENTS")
                            .FontSize(10).Bold().FontColor("#106A2E");
                        foreach (var attachment in report.Attachments)
                        {
                            column.Item().Text($"• {attachment.FileName} ({FormatSize(attachment.SizeBytes)}) - uploaded {attachment.UploadedAt:MMM d, yyyy}")
                                .FontSize(8).FontColor("#4B5563");
                        }
                    }

                    column.Item().PaddingTop(16).Text("Prepared by:").FontSize(9);
                    column.Item().Text(report.CounselorName).FontSize(10).SemiBold();
                    column.Item().Text("Guidance Counselor").FontSize(8).FontColor("#6B7280");
                });

                page.Footer().Column(column =>
                {
                    column.Item().LineHorizontal(0.5f).LineColor("#D1D5DB");
                    column.Item().PaddingTop(3).Row(row =>
                    {
                        row.RelativeItem().Text(text =>
                        {
                            text.Span(string.IsNullOrWhiteSpace(report.ReportNumber) ? $"Report #{report.Id}" : report.ReportNumber)
                                .FontSize(8).FontColor("#6B7280");
                        });

                        row.RelativeItem().AlignRight().Text(text =>
                        {
                            text.Span("Page ").FontSize(8).FontColor("#6B7280");
                            text.CurrentPageNumber().FontSize(8).FontColor("#6B7280");
                            text.Span(" of ").FontSize(8).FontColor("#6B7280");
                            text.TotalPages().FontSize(8).FontColor("#6B7280");
                        });
                    });
                });
            });
        });

        return document.GeneratePdf();
    }

    private static void AddPdfSection(QuestPDF.Fluent.ColumnDescriptor column, string heading, string? text, string color = "#106A2E")
    {
        if (string.IsNullOrWhiteSpace(text)) return;

        column.Item().PaddingTop(8).Text(heading.ToUpperInvariant())
            .FontSize(10).Bold().FontColor(color);

        foreach (var block in text.Replace("\r\n", "\n").Split('\n'))
        {
            var line = block.TrimEnd();
            if (line.Length == 0)
            {
                column.Item().PaddingTop(2);
                continue;
            }

            var bullet = line.TrimStart().StartsWith("- ", StringComparison.Ordinal) ||
                         line.TrimStart().StartsWith("• ", StringComparison.Ordinal);

            column.Item().PaddingLeft(bullet ? 10 : 0)
                .Text(bullet ? "• " + line.TrimStart()[2..].Trim() : line)
                .FontSize(9);
        }
    }
}
